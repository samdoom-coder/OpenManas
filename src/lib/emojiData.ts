export const ALL_EMOJIS: EmojiEntry[] = EMOJI_CATEGORIES.flatMap((c) => c.emojis)

export function searchEmojis(query: string, limit = 120): EmojiEntry[] {
  const q = query.trim().toLowerCase()
  if (!q) return ALL_EMOJIS.slice(0, limit)
  const terms = q.split(/\s+/)
  const scored: { entry: EmojiEntry; score: number }[] = []
  for (const entry of ALL_EMOJIS) {
    const hay = `${entry.n} ${entry.k} ${entry.e}`.toLowerCase()
    let score = 0
    let matchedAll = true
    for (const t of terms) {
      if (entry.n.toLowerCase().startsWith(t)) score += 3
      else if (entry.n.toLowerCase().includes(t)) score += 2
      else if (hay.includes(t)) score += 1
      else {
        matchedAll = false
        break
      }
    }
    if (matchedAll) scored.push({ entry, score })
  }
  scored.sort((a, b) => b.score - a.score)
  return scored.slice(0, limit).map((s) => s.entry)
}

const RECENT_KEY = 'nexus_recent_emojis'
const RECENT_MAX = 24

export function getRecentEmojis(): string[] {
  try {
    const raw = localStorage.getItem(RECENT_KEY)
    if (!raw) return []
    const arr = JSON.parse(raw)
    return Array.isArray(arr) ? arr.filter((x) => typeof x === 'string').slice(0, RECENT_MAX) : []
  } catch {
    return []
  }
}

export function addRecentEmoji(emoji: string) {
  try {
    const cur = getRecentEmojis().filter((e) => e !== emoji)
    cur.unshift(emoji)
    localStorage.setItem(RECENT_KEY, JSON.stringify(cur.slice(0, RECENT_MAX)))
  } catch {
    /* ignore */
  }
}

