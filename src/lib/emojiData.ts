export function searchLucideIcons(query: string, limit = 120): LucideEntry[] {
  const q = query.trim().toLowerCase()
  if (!q) return LUCIDE_ICONS.slice(0, limit)
  const terms = q.split(/\s+/)
  const scored: { entry: LucideEntry; score: number }[] = []
  for (const entry of LUCIDE_ICONS) {
    const hay = `${entry.label} ${entry.name} ${entry.keywords}`.toLowerCase()
    let score = 0
    let ok = true
    for (const t of terms) {
      if (entry.label.toLowerCase().startsWith(t)) score += 3
      else if (entry.label.toLowerCase().includes(t)) score += 2
      else if (hay.includes(t)) score += 1
      else {
        ok = false
        break
      }
    }
    if (ok) scored.push({ entry, score })
  }
  scored.sort((a, b) => b.score - a.score)
  return scored.slice(0, limit).map((s) => s.entry)
}
